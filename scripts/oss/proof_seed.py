#!/usr/bin/env python3
"""Seed the light stack's ``proof`` profile (ADR-0127 D1, hello-cairn WP7).

Writes, under ``deploy/light/.proof/`` (gitignored):

- ``ssh/proof_ed25519`` + ``.pub`` — the keypair the ``sshd`` service trusts and the
  ``remote/run`` legs sign in with (``ssh-keygen``, no passphrase);
- ``proof.env`` — the env the compose profile interpolates: ``COMPOSE_PROFILES=proof`` and
  the loopback ports;

and, beside the compose file, ``deploy/light/.env.infisical`` (gitignored; #2577: loaded only
by the infisical services, never the engine) with throwaway ``INFISICAL_ENCRYPTION_KEY``,
``INFISICAL_AUTH_SECRET`` and ``INFISICAL_DB_PASSWORD`` — generated here only when the file
does not exist, so an operator's own file is never touched.

Every value is generated on this machine for this stack and is never a real secret;
nothing is printed but the paths and the key NAMES. Idempotent: an existing key or value
is kept, so re-running after the stack is up never rotates what the stack was started with.

The Infisical machine identity (``INFISICAL_CLIENT_ID`` / ``_CLIENT_SECRET`` /
``_PROJECT_ID``) is NOT made here, and the proof starts no Infisical server, so the
matrix's Infisical variant of nightly-ops (``profiles/hello-infisical.toml``) stays NOT
PROVED in ``FEATURE_PROOF.md``; the env-secrets variant runs. It can be done without the
web UI: start the stack with ``--profile infisical``, create the first admin and its
organization with Infisical's ``POST /api/v1/admin/bootstrap``, then a project, the
``HELLO_REPORT_TOKEN`` secret and a universal-auth machine identity through its API, and
export the three keys to the engine (the 0.1.2 verification proved the variant that way).

``proof.env`` never carries ``INFISICAL_ENCRYPTION_KEY`` / ``_AUTH_SECRET`` /
``_DB_PASSWORD``: an older seed's copies are dropped on the next run (never moved into
``.env.infisical``), so ``docker compose --env-file .proof/proof.env`` can never hand them
to the engine.

    python scripts/oss/proof_seed.py            # seed (or confirm) the .proof/ directory
    python scripts/oss/proof_seed.py --check    # exit 1 if anything is missing; write nothing
"""
from __future__ import annotations

import argparse
import base64
import os
import secrets
import shutil
import socket
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIGHT = ROOT / "deploy" / "light"
PROOF = LIGHT / ".proof"
SSH_DIR = PROOF / "ssh"
KEY = SSH_DIR / "proof_ed25519"
ENV = PROOF / "proof.env"
INFISICAL_ENV = LIGHT / ".env.infisical"

#: Defaults the compose profile interpolates; a value already in proof.env wins.
DEFAULTS = {
    "COMPOSE_PROFILES": "proof",
    "PROOF_SSH_USER": "cairn",
    "PROOF_SSH_PORT": "2222",
    "PROOF_PG_PORT": "55432",
    "INFISICAL_PORT": "8085",
    "INFISICAL_SITE_URL": "http://localhost:8085",
    "INFISICAL_TELEMETRY_ENABLED": "false",
}
#: Generated once into .env.infisical, kept afterwards (the stack was started with them).
GENERATED = {
    # Infisical wants a 16-byte key as 32 hex chars, and a base64 auth secret.
    "INFISICAL_ENCRYPTION_KEY": lambda: secrets.token_hex(16),
    "INFISICAL_AUTH_SECRET": lambda: base64.b64encode(secrets.token_bytes(32)).decode(),
    "INFISICAL_DB_PASSWORD": lambda: secrets.token_urlsafe(24),
}
#: Added by hand after the identity exists (see the module docstring).
IDENTITY = ("INFISICAL_CLIENT_ID", "INFISICAL_CLIENT_SECRET", "INFISICAL_PROJECT_ID")


def read_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        out[k.strip()] = v.strip()
    return out


def write_env(path: Path, values: dict[str, str]) -> None:
    body = f"# {path.name} — generated by scripts/oss/proof_seed.py; gitignored.\n" \
           "# Throwaway values for the local feature proof. Never copy them anywhere.\n"
    body += "".join(f"{k}={v}\n" for k, v in values.items())
    tmp = path.with_suffix(".tmp")
    tmp.write_text(body, encoding="utf-8")
    os.chmod(tmp, 0o600)
    tmp.replace(path)


def _busy(port: int) -> bool:
    with socket.socket() as s:
        return s.connect_ex(("127.0.0.1", port)) == 0


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def seed_ssh_key() -> bool:
    """Generate the keypair if absent. Returns True when it was generated now."""
    if KEY.is_file() and KEY.with_suffix(".pub").is_file():
        return False
    if shutil.which("ssh-keygen") is None:
        sys.exit("proof_seed: ssh-keygen is not on PATH (needed once, to make the sshd keypair)")
    SSH_DIR.mkdir(parents=True, exist_ok=True)
    os.chmod(SSH_DIR, 0o700)
    for stale in (KEY, KEY.with_suffix(".pub")):
        if stale.exists():
            stale.unlink()
    subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", "cairn-proof", "-f", str(KEY)],
                   check=True, stdout=subprocess.DEVNULL)
    # the sshd container reads the public key as uid 1000: world-readable is what it needs
    os.chmod(KEY, 0o600)
    os.chmod(KEY.with_suffix(".pub"), 0o644)
    return True


def seed(*, check: bool = False) -> int:
    existing = read_env(ENV)
    stale = [k for k in GENERATED if k in existing]   # an older seed put them here: never kept
    for k in stale:
        existing.pop(k)
    infisical = read_env(INFISICAL_ENV)
    if check:
        missing = [k for k in DEFAULTS if k not in existing] + [f"proof.env carries {k}" for k in stale]
        missing += [f".env.infisical:{k}" for k in GENERATED if not infisical.get(k)]
        if not KEY.is_file():
            missing.append("ssh/proof_ed25519")
        if missing:
            print("proof_seed: missing", ", ".join(missing), "— run scripts/oss/proof_seed.py")
            return 1
        print("proof_seed: seeded —", ENV.relative_to(ROOT), ",", INFISICAL_ENV.relative_to(ROOT),
              "and", KEY.relative_to(ROOT))
        return 0
    PROOF.mkdir(parents=True, exist_ok=True)
    os.chmod(PROOF, 0o700)
    made_key = seed_ssh_key()
    values = dict(existing)
    added: list[str] = []
    for k, v in DEFAULTS.items():
        if k not in values:
            if k.endswith("_PORT") and _busy(int(v)):
                v = str(_free_port())
                print(f"proof_seed: loopback port {DEFAULTS[k]} is taken on this machine; {k}={v}")
            values[k] = v
            added.append(k)
    write_env(ENV, values)
    print(f"proof_seed: ssh keypair {'generated' if made_key else 'kept'} at {KEY.relative_to(ROOT)}")
    print(f"proof_seed: {ENV.relative_to(ROOT)} — {'added ' + ', '.join(added) if added else 'unchanged'}"
          + (f"; dropped {', '.join(stale)} (secrets belong in .env.infisical)" if stale else ""))
    if INFISICAL_ENV.is_file():
        short = [k for k in GENERATED if not infisical.get(k)]
        print(f"proof_seed: {INFISICAL_ENV.relative_to(ROOT)} kept (yours)"
              + (f" — it lacks {', '.join(short)}, which the Infisical server needs" if short else ""))
    else:
        write_env(INFISICAL_ENV, {k: make() for k, make in GENERATED.items()})
        print(f"proof_seed: {INFISICAL_ENV.relative_to(ROOT)} written — {', '.join(GENERATED)} (throwaway)")
    identity = [k for k in IDENTITY if values.get(k)]
    if len(identity) < len(IDENTITY):
        print("proof_seed: no Infisical machine identity (made by hand in the UI at "
              f"http://127.0.0.1:{values['INFISICAL_PORT']}); nightly-ops' Infisical variant stays "
              "NOT PROVED, the env-secrets variant runs")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="report what is missing; write nothing")
    args = parser.parse_args(argv)
    return seed(check=args.check)


if __name__ == "__main__":
    sys.exit(main())
