def _render_operator_readme(name: str, ops: list[str]) -> str:
    slug = _slugify(name)
    pkg = f"operator_{name}"
    oplist = "\n".join(f"- `{op}`" for op in ops)
    return textwrap.dedent(f"""\
        # operator-{slug}

        An operator pack (bundle) for the cairn engine. Generated by
        `cairn init operator`. One wheel, {len(ops)} operator(s):

        {oplist}

        ## Layout

        ```
        {name}/
        ├── pyproject.toml            # wheel metadata + cairn.operators entry-points
        ├── pack.toml                 # manifest: kind=operator + [operator."…"] tables
        ├── tests/test_operators.py   # a smoke test per operator (`cairn test .`)
        └── src/{pkg}/
            ├── operators/            # one module per operator (the Operation classes)
            └── schemas/              # one module per operator (pydantic Input/Output)
        ```

        ## Develop

        ```bash
        pip install -e .              # registers every operator with the engine
        cairn ls                  # confirm discovery
        cairn doctor
        cairn test .              # the smoke tests in tests/
        ```

        Each operator's `run()` raises `NotImplementedError` until you implement
        it. Add new operators with another `cairn init operator … --op …`
        (or by hand: a module + schema + an `[operator."…"]` table + an
        entry-point).
        """)


def _render_operator_test(name: str, ops: list[str]) -> str:
    """One smoke test per operator, so ``cairn test <pack>`` has something to run
    from the first minute (an empty ``tests/`` made pytest exit 5, "no tests")."""
    pkg = f"operator_{name}"
    rows = "\n".join(
        f'    ("{op}", "{pkg}.operators.{_op_parts(op)[2]}", "{_op_parts(op)[4]}"),'
        for op in ops)
    return textwrap.dedent('''\
        """Smoke tests for {pkg}. Scaffolded by `cairn init operator`.

        Run them with `cairn test <this pack>`. Once an operator's run() is
        implemented, add a test that calls it with a sample input.
        """
        from __future__ import annotations

        import importlib
        import sys
        from pathlib import Path

        import pytest
        from pydantic import BaseModel

        # The package's own source, so the tests also run before `pip install -e .`.
        sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

        OPERATORS = [
        {rows}
        ]


        @pytest.mark.parametrize("op, module, cls", OPERATORS)
        def test_the_operator_class_imports_with_its_schemas(op, module, cls):
            klass = getattr(importlib.import_module(module), cls)
            assert issubclass(klass.input_schema, BaseModel), op
            assert issubclass(klass.output_schema, BaseModel), op
        ''').format(pkg=pkg, rows=rows)


def _render_operator_changelog() -> str:
    return "# Changelog\n\n## 0.1.0\n\n- Scaffolded by `cairn init operator`.\n"


@app.command("operator")
def init_operator(
    name: str = typer.Argument(
        ..., help="Operator-pack (bundle) name. Must be snake_case.",
    ),
    ops: Optional[list[str]] = typer.Option(
        None, "--op",
        help="An operator as '<group>/<name>' (snake_case both sides). "
             "Repeatable. Defaults to one '<name>/run' operator if omitted.",
    ),
    dest: Optional[str] = typer.Option(
        None, "--dest",
        help="Where to create the bundle dir. Default: ./<name>/.",
    ),
    force: bool = typer.Option(
        False, "--force", help="Overwrite an existing destination.",
    ),
) -> None:
    """Scaffold an operator pack — a wheel that bundles one or more operators."""
    _validate_name(name)
    op_names = list(ops) if ops else [f"{name}/run"]
    parts = [_op_parts(op) for op in op_names]  # validates each --op
    modules = [p[2] for p in parts]
    if len(set(modules)) != len(modules):
        typer.echo(
            "duplicate operator module names — each --op's '<name>' part must "
            f"be unique (got modules {modules}).",
            err=True,
        )
        raise typer.Exit(code=2)

    pkg = f"operator_{name}"
    root = Path(dest) if dest else Path.cwd() / name
    if root.exists() and not force and any(root.iterdir()):
        typer.echo(
            f"refusing to scaffold into non-empty dir (use --force): {root}",
            err=True,
        )
        raise typer.Exit(code=1)

    src = root / "src" / pkg
    _write_file(root / "pyproject.toml", _render_operator_pyproject(name, op_names), force=force)
    _write_file(root / "pack.toml", _render_operator_pack_toml(name, op_names), force=force)
    _write_file(root / "README.md", _render_operator_readme(name, op_names), force=force)
    _write_file(root / "CHANGELOG.md", _render_operator_changelog(), force=force)
    _write_file(src / "__init__.py", _render_operator_pkg_init(name, op_names), force=force)
    _write_file(src / "operators" / "__init__.py", "", force=force)
    _write_file(src / "schemas" / "__init__.py", "", force=force)
    for op in op_names:
        _g, _s, module, _b, _cls = _op_parts(op)
        _write_file(src / "operators" / f"{module}.py", _render_operator_module(name, op), force=force)
        _write_file(src / "schemas" / f"{module}.py", _render_operator_schema(op), force=force)
    for sub in ("docs", "examples"):
        _gitkeep(root / sub)
    _write_file(root / "tests" / "test_operators.py", _render_operator_test(name, op_names),
                force=force)

    typer.echo(f"scaffolded operator pack {root}  ({len(op_names)} operator(s))")
    for op in op_names:
        typer.echo(f"  - {op}")
    typer.echo("")
    typer.echo("next:")
    typer.echo(f"  pip install -e {root}")
    typer.echo("  cairn ls")
    typer.echo(f"  # implement run() in src/{pkg}/operators/*.py")
