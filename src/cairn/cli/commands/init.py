"""``cairn init`` — scaffold a new pack or a single artifact.

Five subcommands:
  - ``init pack <name>``      — full domain pack: one flat directory holding
                                the project root and the importable Python
                                package, plus all asset dirs and runnable
                                hello-world artifacts.
  - ``init operator <name>``  — operator pack (a wheel bundling one or more
                                operators): ``src/operator_<name>/`` layout,
                                ``pack.toml`` with ``kind="operator"`` + one
                                ``[operator."<group>/<op>"]`` table per ``--op``,
                                ``cairn.operators`` entry-points, and stub
                                Operation + pydantic schema modules (no logic).
  - ``init template <name>`` — drop a stub ``*.md`` template into ./templates/.
  - ``init skill <name>``    — drop a stub ``*.md`` skill into ./skills/.
  - ``init policy <name>``   — drop a stub ``*.yaml`` policy into ./policies/.

Design rules locked in this module:

  1. **Every output is runnable.** A scaffolded pack passes
     ``cairn validate`` immediately and exposes a working
     ``examples/sample-trigger.json`` that ``cairn run`` will execute
     (producing TODO output — but no errors). The user fills in TODOs to
     make it useful; they never debug a "missing required field" error
     before writing their own code.

  2. **No surprise overwrites.** The target path must not exist (or must
     be empty) unless ``--force`` is passed. We never edit an existing file.

  3. **Single-artifact subcommands locate the owning pack** by walking up
     from CWD looking for ``pack.toml``. They drop into the corresponding
     sibling asset dir; if no pack root is found, error with a helpful
     message.

  4. **Names must be valid Python identifiers** (snake_case). The PyPI
     slug is auto-derived for ``pyproject.toml``'s ``[project].name``.

  5. **Flat layout.** A pack is ONE directory. That directory is the
     project root (holds ``pyproject.toml``), the importable Python
     package, and the pack root (holds ``pack.toml``). Setuptools is told
     this via ``package-dir = {"<name>" = "."}``. This matches the in-tree
     incident pack layout — one dir, one pack — instead of the nested
     ``project/project/`` shape that duplicates the name.
"""

from __future__ import annotations

import json
import re
import textwrap
from pathlib import Path
from typing import Optional

import typer

app = typer.Typer(
    name="init",
    help="Scaffold a new pack or a single artifact stub.",
    no_args_is_help=True,
)


# ─── shared helpers ─────────────────────────────────────────────────


_PY_IDENT = re.compile(r"^[a-z_][a-z0-9_]*$")


def _validate_name(name: str) -> str:
    """Return ``name`` if valid, else exit with a clear message."""
    if not _PY_IDENT.match(name):
        typer.echo(
            f"invalid name: {name!r}\n"
            f"  must be snake_case (lowercase, digits, underscores; "
            f"start with a letter or underscore).",
            err=True,
        )
        raise typer.Exit(code=2)
    return name


def _slugify(name: str) -> str:
    """Snake → kebab. ``my_pack`` → ``my-pack``. PyPI-style project name."""
    return name.replace("_", "-")


def _find_pack_root(start: Path) -> Optional[Path]:
    """Walk up from ``start`` until a directory containing ``pack.toml``
    is found. Returns that directory, or None.

    Single-artifact subcommands use this so the user can run
    ``cairn init template foo`` from anywhere in the project tree.
    """
    cur = start.resolve()
    while True:
        if (cur / "pack.toml").is_file():
            return cur
        if cur.parent == cur:
            return None
        cur = cur.parent


def _write_file(path: Path, content: str, *, force: bool) -> None:
    """Write ``content`` to ``path``. Refuses to overwrite unless force."""
    if path.exists() and not force:
        typer.echo(f"refusing to overwrite (use --force): {path}", err=True)
        raise typer.Exit(code=1)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


def _gitkeep(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)
    (path / ".gitkeep").touch()


