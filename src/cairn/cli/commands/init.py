        publisher   = "private/TODO"  # "agentops" | "community/<user>" | "private/<org>"
        trust_level = "local"         # "builtin" | "official" | "community" | "private" | "local"

        [compat]
        cairn_engine = ">=0.1.0"

        [assets]
        # Each path is relative to this pack.toml.
        # flows/ + pipelines/ ARE the runnable surface (ADR-0084 D4): a flow is
        # one unit of work, a pipeline composes flows and gates into the thing
        # an operator actually launches.
        flows     = "flows"
        pipelines = "pipelines"
        skills    = "skills"
