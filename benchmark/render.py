"""Write ``benchmark/results/*.json`` into the README's "Proof it works" table.

The README's numbers are generated, so none can drift from its result file or lose its script;
``--check`` fails when they differ, and ``tests/core/test_benchmark_results.py`` runs that check.

    .venv/bin/python benchmark/render.py [--check]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "benchmark" / "results"
README = REPO / "README.md"
BEGIN = "<!-- benchmark:begin (generated by benchmark/render.py; do not edit) -->"
END = "<!-- benchmark:end -->"

_PROVENANCE = ("cairndev_version", "uv_lock_sha256", "git_sha", "code_clean", "machine", "measured_at")
_MACHINE = ("os", "arch", "cpus", "python")


def load_results(results: Path = RESULTS, repo: Path = REPO) -> list[dict]:
    """Every result, refusing one that does not say where it came from."""
    loaded = []
    for path in sorted(results.glob("*.json")):
        result = json.loads(path.read_text(encoding="utf-8"))
        where = result.get("provenance", {})
        missing = [k for k in _PROVENANCE if k not in where]
        missing += [f"machine.{k}" for k in _MACHINE if k not in where.get("machine", {})]
        if missing:
            raise ValueError(f"{path.name} does not record {', '.join(missing)}")
        if where["code_clean"] is not True:
            raise ValueError(f"{path.name} was measured on uncommitted code")
        if not (repo / result["script"]).is_file():
            raise ValueError(f"{path.name} names a script that does not exist: {result['script']}")
        if not result.get("results"):
            raise ValueError(f"{path.name} has no results")
        loaded.append(result)
    if not loaded:
        raise ValueError(f"no results in {results}")
    return loaded


def render_block(results: list[dict]) -> str:
    lines = [BEGIN]
    for result in results:
        where = result["provenance"]
        machine = where["machine"]
        lines += ["", f"**{result['title']}** ([reproduce](./{result['script']}))", "",
                  "| Measured | Result |", "|---|---|"]
        lines += [f"| {row['what']} | {row['result']} |" for row in result["results"]]
        lines += ["", f"cairndev {where['cairndev_version']}, `uv.lock` `{where['uv_lock_sha256'][:12]}`, "
                      f"{machine['os']} {machine['arch']} with {machine['cpus']} CPUs and Python {machine['python']}, "
                      f"{where['measured_at']}."]
    return "\n".join([*lines, "", END])


def replace_block(readme: str, block: str) -> str:
    head, begin, rest = readme.partition(BEGIN)
    _, end, tail = rest.partition(END)
    if not begin or not end:
        raise ValueError("the README has no benchmark markers")
    return f"{head}{block}{tail}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the README differs; change nothing")
    args = parser.parse_args()
    current = README.read_text(encoding="utf-8")
    wanted = replace_block(current, render_block(load_results()))
    if current == wanted:
        return 0
    if args.check:
        print("the README's benchmark table differs from benchmark/results; run benchmark/render.py")
        return 1
    README.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
